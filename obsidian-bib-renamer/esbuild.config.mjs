import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "node:module";
import { copyFileSync, mkdirSync, existsSync } from "node:fs";
import { join } from "node:path";

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = (process.argv[2] === "production");

/** Dossier vault Obsidian cible pour déployer le plugin après build. */
const VAULT_PLUGIN_DIR =
  process.env.OBSIDIAN_PLUGIN_DIR ||
  "D:\\Notes\\.obsidian\\plugins\\booknamer";

function copyToVault() {
  const files = ["main.js", "manifest.json"];
  if (existsSync("styles.css")) {
    files.push("styles.css");
  }

  mkdirSync(VAULT_PLUGIN_DIR, { recursive: true });
  for (const file of files) {
    if (!existsSync(file)) {
      console.warn(`[copy-to-vault] skip missing file: ${file}`);
      continue;
    }
    const dest = join(VAULT_PLUGIN_DIR, file);
    copyFileSync(file, dest);
    console.log(`[copy-to-vault] ${file} -> ${dest}`);
  }
}

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
		...builtinModules.map(m => `node:${m}`),
	],
	format: "cjs",
	target: "es2022",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
});

if (prod) {
	await context.rebuild();
	copyToVault();
	process.exit(0);
} else {
	await context.watch();
}
